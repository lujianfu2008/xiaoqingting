export type Key = keyof (typeof DICT)["zh-CN"];

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s: string = DICT[lang][key] ?? DICT["zh-CN"][key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    }
    return s;
  };
}

// --- current language: module state + subscription (no zustand dependency) ---

let current: Lang = navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  document.documentElement.lang = lang;
  for (const fn of listeners) fn();
}

/** Non-component code (actions, class components): reads the current language. */
export const t: T = (key, vars) => makeT(current)(key, vars);

function subscribe(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Hook: `const t = useT()` — components re-render when the language changes. */
export function useT(): T {
  const lang = useSyncExternalStore(subscribe, getLang);
  return useMemo(() => makeT(lang), [lang]);
}
